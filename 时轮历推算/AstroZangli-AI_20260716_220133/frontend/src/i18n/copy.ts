function chineseCalendarNumber(value: string): string {
  const token = value.replace(/^初/, "");
  if (/^[〇零一二三四五六七八九]{2,4}$/.test(token)) {
    return [...token].map((digit) => CHINESE_DATE_DIGITS[digit]).join("");
  }
  if (token === "正") return "1";
  if (token === "冬") return "11";
  if (token === "腊") return "12";
  if (token.startsWith("廿")) return String(20 + (token.length > 1 ? Number(CHINESE_DATE_DIGITS[token[1]]) : 0));
  if (token.startsWith("卅")) return String(30 + (token.length > 1 ? Number(CHINESE_DATE_DIGITS[token[1]]) : 0));
  if (token === "十") return "10";
  if (token.startsWith("十")) return String(10 + Number(CHINESE_DATE_DIGITS[token[1]]));
  if (token.endsWith("十")) return String(Number(CHINESE_DATE_DIGITS[token[0]]) * 10);
  if (token.length === 2 && token[1] === "十") return String(Number(CHINESE_DATE_DIGITS[token[0]]) * 10);
  if (token.length === 2 && token[0] === "十") return String(10 + Number(CHINESE_DATE_DIGITS[token[1]]));
  return [...token].map((digit) => CHINESE_DATE_DIGITS[digit] ?? digit).join("");
}

